"""Solar array power generation model for DOOMSat 1U CubeSat.

Models 5 active body-mounted triple-junction GaAs solar panels (+X, -X, +Y, -Y, +Z),
cosine incidence angle projection, temperature efficiency derating, orbital eclipse
attenuation, and Maximum Power Point Tracking (MPPT) DC-DC conversion.
"""

from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple
import numpy as np
from numpy.typing import NDArray

from doomsat.core.constants import SOLAR_CONSTANT


@dataclass
class SolarPanelFace:
    """Represents a single body-mounted solar panel face on the CubeSat."""
    name: str
    normal_vector_body: NDArray[np.float64]
    active_area_m2: float = 0.007            # 70 cm^2 active cell area
    nominal_efficiency: float = 0.285        # Triple-junction GaAs (28.5% at 25°C)
    temp_coefficient_per_k: float = -0.0020  # -0.20%/°C efficiency derating
    ref_temperature_k: float = 298.15        # 25°C reference temperature

    def compute_cell_efficiency(self, temperature_k: float) -> float:
        """Compute temperature-derated solar cell conversion efficiency.

        Equation:
            eta(T) = eta_0 * [1 + beta_T * (T - T_ref)]

        Args:
            temperature_k: Panel temperature [K].

        Returns:
            Cell electrical conversion efficiency (dimensionless, clamped >= 0).
        """
        delta_t = temperature_k - self.ref_temperature_k
        eta = self.nominal_efficiency * (1.0 + self.temp_coefficient_per_k * delta_t)
        return max(0.0, float(eta))

    def compute_incident_power(
        self,
        sun_body_unit: NDArray[np.float64],
        solar_flux_w_m2: float = SOLAR_CONSTANT,
        eclipse_factor: float = 1.0,
    ) -> Tuple[float, float]:
        """Compute solar power incident on this panel face.

        Equation:
            cos(theta) = max(0, n_body . s_body)
            P_incident = cos(theta) * A * S_0 * nu

        Args:
            sun_body_unit: Unit vector pointing to Sun in Spacecraft Body frame.
            solar_flux_w_m2: Direct solar flux at 1 AU [W/m^2].
            eclipse_factor: Eclipse shadow factor nu in [0.0, 1.0] (0 = umbra, 1 = direct sunlight).

        Returns:
            Tuple of (incident_power_w, cos_theta_incidence).
        """
        if eclipse_factor <= 0.0:
            return 0.0, 0.0

        cos_theta = float(np.dot(self.normal_vector_body, sun_body_unit))
        cos_theta_proj = max(0.0, cos_theta)
        p_inc = cos_theta_proj * self.active_area_m2 * solar_flux_w_m2 * eclipse_factor
        return p_inc, cos_theta_proj

    def compute_electrical_output(
        self,
        sun_body_unit: NDArray[np.float64],
        temperature_k: float = 298.15,
        solar_flux_w_m2: float = SOLAR_CONSTANT,
        eclipse_factor: float = 1.0,
    ) -> float:
        """Compute raw electrical power generated by this panel face.

        Equation:
            P_elec = P_incident * eta(T)

        Args:
            sun_body_unit: Unit vector pointing to Sun in Body frame.
            temperature_k: Panel temperature [K].
            solar_flux_w_m2: Solar flux [W/m^2].
            eclipse_factor: Eclipse factor nu in [0, 1].

        Returns:
            Raw generated electrical power [W].
        """
        p_inc, _ = self.compute_incident_power(sun_body_unit, solar_flux_w_m2, eclipse_factor)
        if p_inc <= 0.0:
            return 0.0

        eta = self.compute_cell_efficiency(temperature_k)
        return p_inc * eta


class SolarArray:
    """Manages the 5-panel body-mounted solar array and MPPT conversion."""

    def __init__(
        self,
        active_faces: Optional[List[str]] = None,
        panel_area_m2: float = 0.007,
        cell_efficiency: float = 0.285,
        mppt_efficiency: float = 0.92,
    ) -> None:
        """Initialize solar array with 5 active faces (+X, -X, +Y, -Y, +Z).

        Note: -Z face houses the camera payload optics aperture and has no solar cells.
        """
        self.mppt_efficiency = mppt_efficiency
        if active_faces is None:
            active_faces = ["+X", "-X", "+Y", "-Y", "+Z"]

        normals = {
            "+X": np.array([1.0, 0.0, 0.0], dtype=np.float64),
            "-X": np.array([-1.0, 0.0, 0.0], dtype=np.float64),
            "+Y": np.array([0.0, 1.0, 0.0], dtype=np.float64),
            "-Y": np.array([0.0, -1.0, 0.0], dtype=np.float64),
            "+Z": np.array([0.0, 0.0, 1.0], dtype=np.float64),
        }

        self.panels: Dict[str, SolarPanelFace] = {}
        for face in active_faces:
            if face in normals:
                self.panels[face] = SolarPanelFace(
                    name=face,
                    normal_vector_body=normals[face],
                    active_area_m2=panel_area_m2,
                    nominal_efficiency=cell_efficiency,
                )

    def compute_generation(
        self,
        sun_body_unit: Optional[NDArray[np.float64]],
        face_temperatures_k: Optional[Dict[str, float]] = None,
        solar_flux_w_m2: float = SOLAR_CONSTANT,
        eclipse_factor: float = 1.0,
    ) -> Tuple[float, Dict[str, float]]:
        """Compute aggregate solar power generated across all panels with MPPT conversion.

        Args:
            sun_body_unit: Unit vector pointing to Sun in spacecraft body frame.
                           If None or eclipse_factor <= 0, returns 0.0.
            face_temperatures_k: Dict mapping face name to temperature [K]. Defaults to 298.15K.
            solar_flux_w_m2: Direct solar flux [W/m^2].
            eclipse_factor: Eclipse factor nu in [0.0, 1.0].

        Returns:
            Tuple of (total_power_after_mppt_w, dict_of_raw_face_powers_w).
        """
        face_powers: Dict[str, float] = {}

        if sun_body_unit is None or eclipse_factor <= 0.0:
            for face in self.panels:
                face_powers[face] = 0.0
            return 0.0, face_powers

        # Ensure unit vector
        norm = np.linalg.norm(sun_body_unit)
        if norm > 1e-6:
            s_unit = sun_body_unit / norm
        else:
            s_unit = sun_body_unit

        raw_total_power = 0.0
        for name, panel in self.panels.items():
            t_k = 298.15
            if face_temperatures_k and name in face_temperatures_k:
                t_k = face_temperatures_k[name]

            p_face = panel.compute_electrical_output(
                sun_body_unit=s_unit,
                temperature_k=t_k,
                solar_flux_w_m2=solar_flux_w_m2,
                eclipse_factor=eclipse_factor,
            )
            face_powers[name] = p_face
            raw_total_power += p_face

        # Apply MPPT / Boost converter efficiency
        mppt_power = raw_total_power * self.mppt_efficiency
        return mppt_power, face_powers
